-- Restore the mutually-exclusive Outland fishing-hole topology without
-- reusing the incompatible historical pool-ID namespace.
--
-- Project SkyFire database release R23.004 contains 84 complete fishing pools
-- for Steam Pump Flotsam (182952), Sporefish School (182953), and Brackish
-- Mixed School (182954). Exact (entry, map, x/y/z, orientation) matching maps
-- 252 of those members one-to-one to this database. SkyFire's original pool
-- IDs collide here with live creature and gameobject pools, so this migration
-- allocates the verified-free internal range 60004--60087 instead. It neither
-- moves nor deletes existing content. The lone unmatched local 182953 spawn is
-- deliberately not pooled because the source does not identify its group.
--
-- Source:
--   ProjectSkyfire/database R23.004
--   SFDB_full_548_23.004_2023_12_04_Release.zip
--   https://github.com/ProjectSkyfire/database/releases/tag/R23.004

