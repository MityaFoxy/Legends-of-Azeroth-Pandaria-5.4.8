INSERT INTO `pool_template` (`entry`, `max_limit`, `description`)
SELECT
    `restore`.`pool_entry`,
    1,
    CONCAT('Recovered Outland fishing pool (SkyFire R23.004 source pool ',
           `restore`.`source_pool_entry`, ')')
FROM `_outland_fishing_pool_restore` `restore`
LEFT JOIN `pool_template` `existing`
    ON `existing`.`entry` = `restore`.`pool_entry`
WHERE `existing`.`entry` IS NULL
GROUP BY `restore`.`pool_entry`, `restore`.`source_pool_entry`;

INSERT INTO `pool_gameobject` (`guid`, `pool_entry`, `chance`, `description`)
SELECT
    `restore`.`guid`,
    `restore`.`pool_entry`,
    `restore`.`chance`,
    ''
FROM `_outland_fishing_pool_restore` `restore`
INNER JOIN `gameobject` `spawn`
    ON `spawn`.`guid` = `restore`.`guid`
    AND `spawn`.`id` IN (182952, 182953, 182954)
LEFT JOIN `pool_gameobject` `existing`
    ON `existing`.`guid` = `restore`.`guid`
WHERE `existing`.`guid` IS NULL;

